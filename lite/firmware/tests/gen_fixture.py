"""Fixture: lite/fly.py AngleMode (the law the simulator flew) on random attitudes.

The C++ lite::angle_mode must reproduce it (level setpoint, stick throttle = hover
thrust of the nominal vehicle). Writes angle_fixture.hpp.
    python -m lite.firmware.tests.gen_fixture
"""
import json
import os
import types

import torch

from lite.fly import AngleMode

HERE = os.path.dirname(os.path.abspath(__file__))
LITE = os.path.dirname(os.path.dirname(HERE))


def main():
    veh = json.load(open(os.path.join(LITE, "out", "flight.json")))["vehicles"]["nominal"]
    import yaml
    kp = yaml.safe_load(open(os.path.join(LITE, "spec.yaml")))["sim"]["angle_kp"]
    g = torch.Generator().manual_seed(5)
    n = 64
    q = torch.randn(n, 4, generator=g)
    q[:8] = torch.tensor([1.0, 0, 0, 0])            # include level and near-inverted cases
    q[1] = torch.tensor([0.0, 1.0, 0, 0])            # exactly inverted (roll 180)
    q[2] = torch.tensor([0.0, 0.0, 1.0, 0])          # exactly inverted (pitch 180)
    q[3] = torch.tensor([0.9659, 0.2588, 0, 0])      # 30 deg roll
    q[4] = torch.tensor([0.9659, 0, -0.2588, 0])     # 30 deg nose up
    q = q / q.norm(dim=-1, keepdim=True)
    w, x, y, z = q.unbind(-1)
    R = torch.stack([
        torch.stack([1 - 2 * (y * y + z * z), 2 * (x * y - w * z), 2 * (x * z + w * y)], -1),
        torch.stack([2 * (x * y + w * z), 1 - 2 * (x * x + z * z), 2 * (y * z - w * x)], -1),
        torch.stack([2 * (x * z - w * y), 2 * (y * z + w * x), 1 - 2 * (x * x + y * y)], -1)], -2)
    env = types.SimpleNamespace(_R_att=lambda: R)
    a = AngleMode(env, veh, kp)()
    rmax = torch.tensor(veh["max_body_rate"])
    rate = a[:, 1:] * rmax
    F = (a[:, 0] + 1) / 2 * 4 * veh["thrust_max"]
    rows = []
    for i in range(n):
        rows.append("  {{%s}, {%s}, %r}," % (", ".join(f"{float(v)!r}f" for v in q[i]),
                                              ", ".join(f"{float(v)!r}f" for v in rate[i]), float(F[i])))
    hover = veh["mass"] * veh["gravity"]
    src = ["// GENERATED by lite/firmware/tests/gen_fixture.py from lite/fly.py AngleMode -- DO NOT EDIT.",
           "#pragma once", "struct AngleCase { float q[4]; float rate[3]; float thrust; };",
           f"constexpr float kFixtureHoverThrust = {hover!r}f;",
           f"constexpr int kAngleCases = {n};", "constexpr AngleCase kAngle[] = {", *rows, "};", ""]
    open(os.path.join(HERE, "angle_fixture.hpp"), "w").write("\n".join(src))
    print("wrote angle_fixture.hpp,", n, "cases")


if __name__ == "__main__":
    main()
