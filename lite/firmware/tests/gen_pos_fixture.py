"""Fixture: lite/autonomy.py PosHoldLaw (the position-hold law the simulator flew) on random
input sequences. The C++ lite::PositionHold must reproduce every output, step by step, with
its internal state (hold point, integrators) carried along. Writes pos_fixture.hpp.

    python -m lite.firmware.tests.gen_pos_fixture
"""
import os

import torch
import yaml

from lite.autonomy import PosHoldLaw

HERE = os.path.dirname(os.path.abspath(__file__))
LITE = os.path.dirname(os.path.dirname(HERE))
SEQS, STEPS, DT = 8, 200, 1.0 / 500.0


def f(v):
    t = f"{float(v):.9g}"
    return (t if any(c in t for c in ".e") else t + ".0") + "f"   # float32 round-trips in 9 digits


def main():
    import json
    veh = json.load(open(os.path.join(LITE, "out", "flight.json")))["vehicles"]["nominal"]
    cfg = yaml.safe_load(open(os.path.join(LITE, "spec.yaml")))["sim"]["pos_hold"]
    hover = veh["mass"] * veh["gravity"]
    g = torch.Generator().manual_seed(7)
    rows, starts = [], []
    for s in range(SEQS):
        law = PosHoldLaw(1, cfg, hover, DT)
        p = torch.randn(1, 3, generator=g) * 0.5 + torch.tensor([0.0, 0.0, 1.0])
        v = torch.zeros(1, 3)
        law.reset(torch.arange(1), p)
        starts.append(p[0].clone())
        yaw = float(torch.rand(1, generator=g) * 6.28 - 3.14)
        mode, flow_age, z_valid = 0, 0.0, True
        cmd = torch.zeros(1, 3)
        for k in range(STEPS):
            # piecewise inputs: modes, commands, flow gaps and height loss all change mid-sequence
            r = float(torch.rand(1, generator=g))
            if r < 0.02:
                mode = int(torch.randint(0, 3, (1,), generator=g))
            if r > 0.97:
                cmd = torch.zeros(1, 3) if float(torch.rand(1, generator=g)) < 0.5 else torch.randn(1, 3, generator=g) * 0.6
            if 0.30 < r < 0.32:
                flow_age = float(torch.rand(1, generator=g)) * 1.5     # a gap of up to 1.5 s
            flow_age = flow_age + DT if flow_age > 0.0 else 0.0
            if flow_age > 1.6:
                flow_age = 0.0
            if 0.50 < r < 0.505:
                z_valid = not z_valid
            v = v * 0.98 + torch.randn(1, 3, generator=g) * 0.05
            p = p + v * DT + torch.randn(1, 3, generator=g) * 0.002
            yaw += float(torch.randn(1, generator=g)) * 0.01
            m = torch.tensor([mode])
            fa = torch.tensor([flow_age], dtype=torch.float32)
            zv = torch.tensor([z_valid])
            roll, pitch, thrust = law.step(p, v, torch.tensor([yaw], dtype=torch.float32), cmd, m, fa, zv)
            rows.append("  {{%s}, {%s}, %s, {%s}, %d, %s, %d, {%s, %s, %s}}," % (
                ", ".join(f(x) for x in p[0]), ", ".join(f(x) for x in v[0]), f(torch.tensor(yaw, dtype=torch.float32)),
                ", ".join(f(x) for x in cmd[0]), mode, f(fa[0]), int(z_valid), f(roll[0]), f(pitch[0]), f(thrust[0])))
    src = ["// GENERATED by lite/firmware/tests/gen_pos_fixture.py from lite/autonomy.py PosHoldLaw -- DO NOT EDIT.",
           "#pragma once",
           "struct PosCase { float p[3]; float v[3]; float yaw; float cmd[3]; int mode; float flow_age; int z_valid;"
           " float out[3]; };",
           f"constexpr float kPosFixtureHover = {f(hover)};",
           f"constexpr float kPosFixtureDt = {f(DT)};",
           f"constexpr int kPosSeqs = {SEQS};", f"constexpr int kPosSteps = {STEPS};",
           "constexpr float kPosStart[][3] = {" + ", ".join("{%s}" % ", ".join(f(x) for x in st) for st in starts) + "};",
           "constexpr PosCase kPos[] = {", *rows, "};", ""]
    open(os.path.join(HERE, "pos_fixture.hpp"), "w").write("\n".join(src))
    print("wrote pos_fixture.hpp,", SEQS, "x", STEPS, "steps")


if __name__ == "__main__":
    main()
