"""Write the Lite's nf/vehicle_params.hpp from the vehicle the flight sim flew.

    python -m lite.firmware.gen_params      (after python -m lite.checks && python -m lite.fly)

Same layout as neuroflight-fc tools/gen_params.py, so nf_core compiles unchanged;
plus the Lite's angle-mode gain. Source: lite/out/flight.json vehicles.nominal.
"""
from __future__ import annotations

import hashlib
import json
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
LITE = os.path.dirname(HERE)
DST = os.path.join(HERE, "libraries", "nf_core", "src", "nf", "vehicle_params.hpp")


def arr(v):
    return "{" + ", ".join(f"{float(x)!r}f" for x in v) + "}"


def main():
    src = os.path.join(LITE, "out", "flight.json")
    raw = open(src, "rb").read()
    v = json.loads(raw)["vehicles"]["nominal"]
    with open(os.path.join(LITE, "spec.yaml")) as f:
        sim = yaml.safe_load(f)["sim"]
    ph = sim["pos_hold"]
    lines = [
        "// GENERATED by lite/firmware/gen_params.py from lite/out/flight.json (vehicles.nominal) -- DO NOT EDIT.",
        f"// source sha256[:16] = {hashlib.sha256(raw).hexdigest()[:16]}",
        "#pragma once", "", "namespace nf {", "namespace vehicle {", "",
        f"constexpr float kMass = {float(v['mass'])!r}f;",
        f"constexpr float kInertia[3] = {arr(v['inertia'])};",
        f"constexpr float kArmXy = {float(v['arm_xy'])!r}f;",
        f"constexpr float kThrustMax = {float(v['thrust_max'])!r}f;",
        f"constexpr float kThrustCurveA = {float(v['thrust_curve_a'])!r}f;",
        f"constexpr float kYawTorqueCoeff = {float(v['yaw_torque_coeff'])!r}f;",
        f"constexpr float kMotorTauUp = {float(v['motor_tau_up'])!r}f;",
        f"constexpr float kMotorTauDown = {float(v['motor_tau_down'])!r}f;",
        f"constexpr float kIdleCommand = {float(v['idle_command'])!r}f;",
        f"constexpr float kLinDrag[3] = {arr(v['lin_drag'])};",
        f"constexpr float kRotDrag[3] = {arr(v['rot_drag'])};",
        f"constexpr float kGravity = {float(v['gravity'])!r}f;",
        f"constexpr int kControlRateHz = {int(v['control_rate_hz'])};",
        f"constexpr int kRateLoopHz = {int(v['rate_loop_hz'])};",
        f"constexpr float kLatencyS = {float(v['latency_s'])!r}f;",
        f"constexpr float kMaxBodyRate[3] = {arr(v['max_body_rate'])};",
        "", "// NF-3D Lite only: angle-mode outer loop (lite/fly.py AngleMode)",
        f"constexpr float kAngleKp[2] = {arr(sim['angle_kp'])};",
        "", "// NF-3D Lite v3 only: position hold (lite/autonomy.py PosHoldLaw, spec.yaml sim.pos_hold)",
        f"constexpr float kPosKp[3] = {arr(ph['kp_pos'])};",
        f"constexpr float kVelKp[3] = {arr(ph['kp_vel'])};",
        f"constexpr float kVelKi[3] = {arr(ph['ki_vel'])};",
        f"constexpr float kVelILimit[3] = {arr(ph['i_limit'])};",
        f"constexpr float kVelMax[3] = {arr(ph['v_max'])};",
        f"constexpr float kCmdVelMax[3] = {arr(ph['cmd_v_max'])};",
        f"constexpr float kAccMaxXy = {float(ph['a_max_xy'])!r}f;",
        f"constexpr float kPosMaxTilt = {float(ph['max_tilt_rad'])!r}f;",
        "", "}  // namespace vehicle", "}  // namespace nf", ""]
    with open(DST, "w") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.relpath(DST, os.path.dirname(LITE)))


if __name__ == "__main__":
    main()
